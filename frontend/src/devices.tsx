import { Select } from './select';
import { useEffect, useState } from 'react';
import { ApiError, errorText, request } from './api';
import { Button, Choices, Field, Heading } from './ui';
import type { DeviceStatus, PairingCode } from './run-api';

const executionModes = {
  heartbeat: 'Connection only',
  demo: 'Local Git only',
  'demo-agents': 'Local Git + Agent demo',
  github: 'GitHub repository only',
  'codex-agents': 'GitHub + local Codex',
};

export function DevicesPage({ csrf, onUnauthorized }: { csrf: string; onUnauthorized: () => void }) {
  const [devices, setDevices] = useState<DeviceStatus[] | null>(null);
  const [error, setError] = useState('');
  const [pair, setPair] = useState<PairingCode>();
  const [pending, setPending] = useState(false);
  const [refresh, setRefresh] = useState(0);
  const [now, setNow] = useState(Date.now());
  const [executionMode, setExecutionMode] = useState<keyof typeof executionModes>('heartbeat');
  useEffect(() => {
    const control = new AbortController();
    async function load() {
      try {
        const value = await request<{ items: DeviceStatus[] }>('/devices', { signal: control.signal });
        if (!control.signal.aborted) { setDevices(value.items); setError(''); }
      } catch (err) {
        if (control.signal.aborted) return;
        if (err instanceof ApiError && err.status === 401) onUnauthorized();
        else setError(errorText(err));
      }
    }
    void load();
    const timer = window.setInterval(() => { setNow(Date.now()); if (!document.hidden) void load(); }, 5000);
    return () => { control.abort(); window.clearInterval(timer); };
  }, [refresh, onUnauthorized]);

  async function pairDevice() {
    if (pending) return;
    setPending(true); setError('');
    try { setPair(await request<PairingCode>('/devices/pair', { method: 'POST', csrf })); setNow(Date.now()); }
    catch (err) {
      if (err instanceof ApiError && err.status === 401) onUnauthorized(); else setError(errorText(err));
    } finally { setPending(false); }
  }
  const expired = !!pair && Date.parse(pair.expiresAt) <= now;
  const github = executionMode === 'github' || executionMode === 'codex-agents';
  const executeAgents = executionMode === 'demo-agents' || executionMode === 'codex-agents';
  const command = 'java -jar platform/target/agentship-platform-0.1.0-SNAPSHOT.jar --worker --platform '
    + window.location.origin + ' --state-dir .agentship/' + (github ? 'local-worker-github' : 'local-worker') + ' --port 4781 --name "my computer"'
    + (executionMode === 'heartbeat' ? '' : ' --execute-git')
    + (executeAgents ? ' --execute-agents' : '')
    + (github ? ' --mode codex --git-provider github' : '')
    + (pair && !expired ? ' --pair-code ' + pair.code : ' --pair-code <pairing code>');
  return <>
    <Heading label="YOUR EXECUTION DEVICE" title="Local devices" text="Runs stay bound to the computer that starts them. Progress is saved while it is offline and resumes when it reconnects."
      actions={<Button onClick={() => setRefresh(n => n + 1)}>Refresh devicess</Button>} />
    <div className="device-layout">
      <section className="panel"><p className="eyebrow">CONNECT THIS COMPUTER</p><h2>Pair current computer</h2>
        <p className="subtle">After generating the pairing code, run the following command in the project directory of this computer. The executor will continue to connect to the platform.</p>
        <Button variant="accent" disabled={pending} onClick={() => void pairDevice()}>{pending ? 'Generating…' : 'Generate pairing code'}</Button>
        {pair && <div className={'pair-code ' + (expired ? 'expired' : '')} aria-live="polite"><small>{expired ? 'The pairing code has expired, please regenerate it' : 'One-time pairing code'}</small><strong>{pair.code}</strong><span>Valid until {new Date(pair.expiresAt).toLocaleTimeString()}</span></div>}
        <div className="device-execution-mode"><Field label="Local execution mode"><Select aria-label="Local execution mode" value={executionMode} onChange={e => setExecutionMode(e.target.value as typeof executionMode)}>
          <Choices entries={executionModes} />
        </Select></Field></div>
        <ol className="device-instructions"><li>Prepare the Java program generated by the project package and Java 21 on the current computer.</li><li>Open the terminal, enter the project directory, and execute:</li></ol>
        <pre className="worker-command" aria-label="Local worker command"><code>{command}</code></pre>
        <p className="subtle">When restarting a paired program, use the same state-dir and remove the --pair-code parameter.</p>
        {executionMode === 'heartbeat' && <p className="device-note">This mode provides pairing and connection status. Select the local demo to verify branch preparation and node scheduling.</p>}
        {executionMode === 'demo' && <p className="device-note">Requires native Git. The executor will prepare a branch in the local demo repository.</p>}
        {executionMode === 'demo-agents' && <p className="device-note">Requires native Git. The node role is run with the demo results to verify sub-agent order, reconciliation rollups, and end nodes.</p>}
        {github && <div className="device-note">
          <p>GitHub mode will create a public repository or reuse an existing repository according to the running plan, and prepare working branches.</p>
          <p>AGENTSHIP_GITHUB_TOKEN is configured in the terminal environment and the credentials are read by the native program.</p>
          {executeAgents && <p>First install Git and Codex CLI, and log in to Codex locally. Node artifacts are saved in the workspace of the originating computer.</p>}
          <p>The first time you use the GitHub device directory, you need to pair it separately. When paired, stop the original execution program and restart using the same directory.</p>
        </div>}
      </section>
      <section className="panel"><div className="row between"><h2>My devices</h2><span className="pill">{devices?.length ?? '—'} devices</span></div>
        {devices === null ? <p role="status">Reading device...</p> : devices.length === 0 ? <div className="empty"><h3>No computer paired yet</h3><p>Generate the pairing code and start the native program, the device will be displayed here.</p></div> :
          <div className="device-list">{devices.map(device => <article className="device-card" key={device.id}>
            <div className="row between"><h3>{device.name}</h3><span className={'pill ' + (device.connectivity === 'online' ? 'good' : 'attn')}>{device.connectivity === 'online' ? 'Online' : 'Offline'}</span></div>
            <p>{device.mode === 'demo' ? 'Development demo mode' : 'Codex mode'} · {device.codexStatus === 'not_required' ? 'Demo mode does not require Codex' : device.codexStatus === 'available' ? 'Codex CLI detected' : device.codexStatus === 'unavailable' ? 'Codex is not available' : 'Codex status to be confirmed'}</p>
            {device.lastSeenAt && <small>recent connections {new Date(device.lastSeenAt).toLocaleString()}</small>}
          </article>)}</div>}
      </section>
    </div>
    {error && <p role="alert" className="inline-error">{error}</p>}
  </>;
}
